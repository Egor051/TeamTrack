vi.mock('@/components/ui/error-message', () => ({ ErrorMessage: 'ErrorMessage' }));
import ProjectScreen from '@/app/(app)/projects/[id]';
let screen: ReactTestRenderer;
afterEach(async () => { await act(async () => screen?.unmount()); });
it('archive tabs never change active overview; actual server archive/restore updates it', async () => {
  Object.assign(globalThis, { IS_REACT_ACT_ENVIRONMENT: true }); f.count = 2;
  f.stats.mockImplementation(async (_id: string, archived: boolean) => [{ id: archived ? 'archived' : 'active', title: 'Stage', status: archived ? 'archived' : 'in_progress', assignees: [], itemCount: archived ? 50 : f.count, completedCount: archived ? 50 : 1, progressPercent: archived ? 100 : 50 }]);
  await act(async () => { screen = create(createElement(ProjectScreen)); });
  const overview = () => screen.root.findAll((node) => node.type as unknown === 'Progress')[0].props;
  expect(overview()).toMatchObject({ value: 50, label: '1 этап · 1 из 2 пунктов выполнено' });
  const tabs = screen.root.findByProps({ accessibilityLabel: 'Этапы проекта' });
  await act(async () => tabs.props.onChange('archived'));
  expect(overview()).toMatchObject({ value: 50, label: '1 этап · 1 из 2 пунктов выполнено' });
  f.count = 3;
  await act(async () => screen.root.find((node) => node.type as unknown === 'ScrollView' && Boolean(node.props.refreshControl)).props.refreshControl.props.onRefresh());
  expect(overview().label).toBe('1 этап · 1 из 3 пунктов выполнено');
  await act(async () => tabs.props.onChange('active'));
  expect(overview().label).toBe('1 этап · 1 из 3 пунктов выполнено');
});
