-- Caller must be authenticated; returns auth.uid() or raises.
create function private.require_auth()
returns uuid
language plpgsql
stable
security definer
set search_path = private, public
as $$
declare
    v_user uuid := auth.uid();
begin
    if v_user is null then
        raise exception 'authentication required'
            using errcode = 'insufficient_privilege'; -- 42501
    end if;
    return v_user;
end
$$;

-- Role of a user in a project; null when the user is not a project member.
create function private.project_role_of(p_project_id uuid, p_user_id uuid default auth.uid())
returns public.project_role
language sql
stable
security definer
set search_path = private, public
as $$
    select pm.role
    from public.project_members pm
    where pm.project_id = p_project_id
      and pm.user_id = p_user_id;
$$;

create function private.is_project_member(p_project_id uuid, p_user_id uuid default auth.uid())
returns boolean
language sql
stable
security definer
set search_path = private, public
as $$
    select private.project_role_of(p_project_id, p_user_id) is not null;
$$;

