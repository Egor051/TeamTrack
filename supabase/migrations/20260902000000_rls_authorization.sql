-- TaskTrace — RLS policies, authorization helpers and security-definer RPCs.
-- Migration 0002. Requires 20260901000000_initial_schema.sql to be applied.
--
-- Design:
--   * Authorization helpers live in schema `private` (not exposed via PostgREST,
--     which only serves `public`/configured schemas). All helpers are
--     SECURITY DEFINER with a fixed search_path so that:
--       - RLS policy predicates cannot recurse into RLS-protected tables;
--       - policy subqueries cannot be tampered with via search_path;
--       - callers cannot alter their behaviour.
--   * Every sensitive write operation is a SECURITY DEFINER RPC in `public`
--     that performs its own authorization. `is_completed` on task_items can
--     ONLY be changed through set_task_item_state() because direct
--     INSERT/UPDATE on task_items is revoked from anon/authenticated.
--   * item_actions and audit_log are SELECT-only for authenticated; INSERTs
--     happen exclusively inside server-side RPCs / triggers.
--   * All timestamps are timestamptz generated by PostgreSQL (now());
--     user identity comes from auth.uid() — never from client input.
--
-- Supabase compatibility: if the standard Supabase roles (anon, authenticated,
-- service_role) do not exist (plain PostgreSQL), they are created here.

create extension if not exists pgcrypto;

-- -----------------------------------------------------------------------------
-- Supabase roles (no-op on hosted Supabase)
-- -----------------------------------------------------------------------------

do $$
begin
    if not exists (select 1 from pg_roles where rolname = 'anon') then
        create role anon nologin noinherit;
    end if;
    if not exists (select 1 from pg_roles where rolname = 'authenticated') then
        create role authenticated nologin noinherit;
    end if;
    if not exists (select 1 from pg_roles where rolname = 'service_role') then
        create role service_role nologin noinherit bypassrls;
    end if;
end
$$;

-- -----------------------------------------------------------------------------
-- Private schema for internal authorization helpers
-- -----------------------------------------------------------------------------

create schema if not exists private;

revoke all on schema private from public;

-- -----------------------------------------------------------------------------
-- Authorization helper functions (SECURITY DEFINER, fixed search_path)
