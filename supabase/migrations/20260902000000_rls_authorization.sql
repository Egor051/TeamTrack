-- Archive a task item (owner/admin). History is preserved.
create function public.archive_task_item(p_task_item_id uuid)
returns void
language plpgsql
security definer
set search_path = private, public
as $$
declare
    v_user uuid := private.require_auth();
    r public.task_items%rowtype;
begin
    select * into r from public.task_items where id = p_task_item_id;

    if not found then
        raise exception 'task item not found';
    end if;
    if not private.is_project_admin(private.task_project_id(r.task_id)) then
        raise exception 'only owner/admin can archive task items'
            using errcode = 'insufficient_privilege';
    end if;
    if not private.task_is_editable(r.task_id) then
        raise exception 'task is archived';
    end if;
    if r.is_archived then
        return; -- idempotent no-op
    end if;

    update public.task_items
    set is_archived = true, archived_at = now()
    where id = r.id;

    insert into public.audit_log (project_id, user_id, action, entity_type, entity_id, old_data, new_data)
    select t.project_id, v_user, 'archived', 'task_item', r.id,
           jsonb_build_object('is_archived', false),
           jsonb_build_object('is_archived', true)
    from public.tasks t where t.id = r.task_id;
end
$$;

