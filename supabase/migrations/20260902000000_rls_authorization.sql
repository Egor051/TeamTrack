-- Remove a project member (owner/admin only). Removing the owner is forbidden
-- — transfer ownership first. The removed user also loses access to all tasks
-- of the project (task_members + task_assignees are cleaned up atomically).
create function public.remove_project_member(p_project_id uuid, p_user_id uuid)
returns void
language plpgsql
security definer
set search_path = private, public
as $$
declare
    v_user uuid := private.require_auth();
    v_role public.project_role;
begin
    if not private.is_project_admin(p_project_id) then
        raise exception 'only owner/admin can manage project members'
            using errcode = 'insufficient_privilege';
    end if;
    if not private.project_is_active(p_project_id) then
        raise exception 'project is archived';
    end if;

    select role into v_role
    from public.project_members
    where project_id = p_project_id and user_id = p_user_id;

    if not found then
        return; -- idempotent no-op
    end if;
    if v_role = 'owner' then
        raise exception 'cannot remove the project owner — transfer ownership first';
    end if;

    delete from public.task_assignees a
    using public.tasks t
    where a.task_id = t.id
      and t.project_id = p_project_id
      and a.user_id = p_user_id;

    delete from public.task_members m
    using public.tasks t
    where m.task_id = t.id
      and t.project_id = p_project_id
      and m.user_id = p_user_id;

    delete from public.project_members
    where project_id = p_project_id and user_id = p_user_id;

    insert into public.audit_log (project_id, user_id, action, entity_type, entity_id, old_data)
    values (p_project_id, v_user, 'member_removed', 'project_member', p_user_id,
            jsonb_build_object('user_id', p_user_id, 'role', v_role));
end
$$;

-- Change a member role.
--  * owner may change roles of admin/member/viewer;
--  * admin may change roles of member/viewer only (including self-demotion),
--    never of another admin and never of the owner;
--  * the 'owner' role itself can only change via transfer_project_ownership.
create function public.change_member_role(p_project_id uuid, p_user_id uuid, p_new_role public.project_role)
returns void
language plpgsql
security definer
set search_path = private, public
as $$
declare
    v_user        uuid := private.require_auth();
    v_caller_role public.project_role := private.project_role_of(p_project_id);
    v_target_role public.project_role := private.project_role_of(p_project_id, p_user_id);
begin
    if v_caller_role not in ('owner', 'admin') then
        raise exception 'only owner/admin can change roles'
            using errcode = 'insufficient_privilege';
    end if;
    if v_target_role is null then
        raise exception 'target user is not a project member';
    end if;
    if v_target_role = 'owner' then
        raise exception 'the owner role can only be changed via transfer_project_ownership';
    end if;
    if p_new_role = 'owner' then
        raise exception 'use transfer_project_ownership to set a new owner';
    end if;
    if v_caller_role = 'admin' and v_target_role = 'admin' and p_user_id <> v_user then
        raise exception 'admin cannot change the role of another admin'
            using errcode = 'insufficient_privilege';
    end if;
    if not private.project_is_active(p_project_id) then
        raise exception 'project is archived';
    end if;

    update public.project_members
    set role = p_new_role
    where project_id = p_project_id and user_id = p_user_id;

    insert into public.audit_log (project_id, user_id, action, entity_type, entity_id, old_data, new_data)
    values (p_project_id, v_user, 'role_changed', 'project_member', p_user_id,
            jsonb_build_object('user_id', p_user_id, 'role', v_target_role),
            jsonb_build_object('user_id', p_user_id, 'role', p_new_role));
end
$$;

-- Atomic ownership transfer: old owner -> admin, new owner -> owner.
-- Only the current owner may call this.
create function public.transfer_project_ownership(p_project_id uuid, p_new_owner_id uuid)
returns void
language plpgsql
security definer
set search_path = private, public
as $$
declare
    v_user     uuid := private.require_auth();
    v_new_role public.project_role := private.project_role_of(p_project_id, p_new_owner_id);
begin
    if not private.is_project_owner(p_project_id) then
        raise exception 'only the current owner can transfer ownership'
            using errcode = 'insufficient_privilege';
    end if;
    if p_new_owner_id = v_user then
        raise exception 'cannot transfer ownership to yourself';
    end if;
    if v_new_role is null then
        raise exception 'new owner must be a project member';
    end if;
    if not private.project_is_active(p_project_id) then
        raise exception 'project is archived';
    end if;

    update public.project_members set role = 'admin'
    where project_id = p_project_id and user_id = v_user;

    update public.project_members set role = 'owner'
    where project_id = p_project_id and user_id = p_new_owner_id;

    insert into public.audit_log (project_id, user_id, action, entity_type, entity_id, old_data, new_data)
    values (p_project_id, v_user, 'role_changed', 'project_member', v_user,
            jsonb_build_object('user_id', v_user, 'role', 'owner'),
            jsonb_build_object('user_id', v_user, 'role', 'admin')),
           (p_project_id, v_user, 'role_changed', 'project_member', p_new_owner_id,
            jsonb_build_object('user_id', p_new_owner_id, 'role', v_new_role),
            jsonb_build_object('user_id', p_new_owner_id, 'role', 'owner'));
end
$$;

