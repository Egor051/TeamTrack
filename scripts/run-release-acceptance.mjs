// All database suites use an owned tmpfs PostgreSQL container. The existing
// local stack is a schema provider only; no app DB or production URL is used.
import { spawn, spawnSync } from 'node:child_process';
import { copyFileSync,createWriteStream, existsSync,mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { docker, securityDatabaseContainers, root } from './security-test-harness.mjs';
const out = resolve('.expo', 'release-acceptance'); mkdirSync(out, { recursive: true });
const name = 'tasktrace-security-postgres-' + process.pid;
const { providerContainer } = securityDatabaseContainers();
const network = docker(['inspect', providerContainer, '--format', '{{.HostConfig.NetworkMode}}']);
const image = 'public.ecr.aws/supabase/postgres:17.11.0.004';
const suites = [
 ['schema-compatibility', 'scripts/release-schema-compatibility.mjs'],
 ['blockers', 'scripts/release-blockers-integration.mjs'],
 ['sql-fresh', 'scripts/run-audit-sql-tests.mjs', '--fresh'],
 ['sql-upgrade', 'scripts/run-audit-sql-tests.mjs', '--cron', '--advisors', '--generate-types'],
 ['v3-fresh', 'scripts/operation-window-integration.mjs'],
 ['v3-upgrade', 'scripts/operation-window-integration.mjs', '--upgrade'],
 ['audit-fixes-fresh', 'scripts/audit-fixes-integration.mjs'],
 ['audit-fixes-upgrade', 'scripts/audit-fixes-integration.mjs', '--upgrade'],
 ['security-fresh', 'scripts/test-security-hardening.mjs'],
 ['security-upgrade', 'scripts/test-security-hardening.mjs', '--hosted'],
 ['cross-tab-chromium', 'scripts/regression-mutation-browser.mjs', '--repeat=100'],
 ['cross-tab-webkit', 'scripts/regression-mutation-browser.mjs', '--webkit', '--repeat=100'],
 ['storage-chromium', 'scripts/release-storage-browser.mjs'],
 ['storage-webkit', 'scripts/release-storage-browser.mjs', '--webkit'],
 ['v3-load', 'scripts/operation-window-load.mjs'],
 ['gc-scale', 'scripts/release-gc-scale.mjs'],
 ['ui', 'scripts/run-security-integrations.mjs', 'scripts/operation-window-ui-browser.mjs', 'scripts/audit-fixes-browser.mjs'],
 ['crash', 'scripts/operation-window-crash.mjs'],
];
const requested = process.argv.slice(2);
if (requested.some(label => !suites.some(s => s[0] === label))) throw Error('Unknown release acceptance suite');
const results = []; let failed = false;
try {
 docker(['run','-d','--name',name,'--network',network,'-p','127.0.0.1::5432','--tmpfs','/var/lib/postgresql/data','-e','POSTGRES_PASSWORD=postgres',image,'postgres','-D','/etc/postgresql','-c','listen_addresses=*']);
 let ready = false;
 for (let n=0;n<180;n++) {
  if (spawnSync('docker',['exec',name,'pg_isready','-h','127.0.0.1','-U','postgres'],{windowsHide:true}).status===0) { ready=true; break; }
  await new Promise(r=>setTimeout(r,200));
 }
 if (!ready) throw Error('Disposable PostgreSQL startup failed');
 for (const [label,script,...args] of suites.filter(s=>!requested.length || requested.includes(s[0]))) {
  const started=Date.now(), logPath=resolve(out,label+'.log');
  if(existsSync(logPath)) {
   const attempts=resolve(out,'attempts');mkdirSync(attempts,{recursive:true});
   copyFileSync(logPath,resolve(attempts,label+'-'+started+'.log'));
  }
  const log=createWriteStream(logPath);
  const exitCode=await new Promise((done,reject)=>{
   const childEnv={...process.env,TASKTRACE_SECURITY_POSTGRES_CONTAINER:name,EXPO_NO_DOTENV:'1'};
   // The crash suite creates/kills its own server and requires the original
   // schema provider inventory, not this runner's disposable server override.
   if(label==='crash')delete childEnv.TASKTRACE_SECURITY_POSTGRES_CONTAINER;
   const child=spawn(process.execPath,[script,...args],{cwd:root,env:childEnv,windowsHide:true});
   child.stdout.pipe(log,{end:false}); child.stderr.pipe(log,{end:false}); child.on('error',reject); child.on('exit',done);
  });
  await new Promise(r=>log.end(r));
  const actualImage=label==='crash'?docker(['inspect',providerContainer,'--format','{{.Config.Image}}']):image;
  results.push({label,script,args,exitCode,elapsedMs:Date.now()-started,image:actualImage}); failed ||= exitCode!==0;
  writeFileSync(resolve(out,'results-'+(requested.join('-')||'all')+'.json'),JSON.stringify(results,null,2)+'\n');
  console.log(label+' exit='+exitCode+' ms='+(Date.now()-started));
 }
} finally {
 // Exact name generated by this process, never an existing Supabase container.
 spawnSync('docker',['rm','-f',name],{windowsHide:true});
}
if (failed) process.exitCode=1;
